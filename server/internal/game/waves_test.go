// TestLoadRoomRNGConsumptionInvariant locks the exact MobRNG call sequence
// that LoadRoom performs. The order is mandated by
// docs/specs/foundations/07-determinism-seeding.md and is the foundation of
// BUG-01 — Mob Seed Optimization. Any reorder or miscount of RNG calls in
// LoadRoom, SeedMob, or seedWaves will shift these golden values and fail
// this test.
//
// Canned layout exercises:
//   - Initial enemies spawned in ascending EntityID order.
//   - Wave 0 kept (threshold rounds to ≥1 living).
//   - Wave 1 skipped (threshold rounds to 0) — MUST consume zero RNG.
//   - Wave 2 beyond len(WaveTriggers) — MUST consume zero RNG.
//
// With InitialPop = 2 and WaveTriggers = [0.66, 0.33]:
//
//	floor(2 * 0.66) = 1 → wave 0 kept
//	floor(2 * 0.33) = 0 → wave 1 skipped
//
// Do NOT update the golden values to make this test pass. Shifted values
// mean the RNG consumption order changed — that invalidates every
// pre-computed BUG-01 seed. Fix the code, not the golden.
func TestLoadRoomRNGConsumptionInvariant(t *testing.T) {
	if len(WaveTriggers) < 2 || WaveTriggers[0] != 0.66 || WaveTriggers[1] != 0.33 {
		t.Fatalf("test assumes WaveTriggers=[0.66,0.33]; update the golden first if tuning")
	}

	tmpl := &RoomTemplate{TilemapID: "test"}
	// Deliberately out-of-order — LoadRoom must sort ascending by
	// EntityID before seeding.
	enemies := []EnemySpawnDef{
		{EntityID: 2, Type: EnemyGrunt, X: 400, Y: 300},
		{EntityID: 1, Type: EnemyGrunt, X: 500, Y: 300},
	}
	waves := []WaveDef{
		{Mobs: []WaveMobDef{{Type: EnemyGrunt, X: 600, Y: 300}}},
		{Mobs: []WaveMobDef{{Type: EnemyGrunt, X: 700, Y: 300}}},
		{Mobs: []WaveMobDef{{Type: EnemyGrunt, X: 800, Y: 300}}},
	}

	const seed = int64(42)
	rng := rand.New(rand.NewSource(seed))
	r := NewRoomState(0) // room 0 = no wall grid; positions pass through clean
	now := time.Unix(1_700_000_000, 0)
	_ = LoadRoom(r, rng, tmpl, enemies, waves, now)

	// Post-condition: skip rule honored.
	if len(r.PendingWaves) != 1 {
		t.Fatalf("expected 1 pending wave (wave 0 kept; wave 1 skipped; wave 2 beyond table), got %d", len(r.PendingWaves))
	}

	// Post-condition: the initial-enemy order is ascending EntityID.
	// Enemy 1 was declared second but seeded first — its AttackCooldown
	// was derived from the FIRST firstAttackDelay Intn(500) call.
	e1 := r.Enemies[1]
	e2 := r.Enemies[2]
	if e1 == nil || e2 == nil {
		t.Fatalf("expected enemies 1 and 2, got %v", r.Enemies)
	}

	// Lock the next 8 RNG values after LoadRoom completes. If any upstream
	// RNG consumer changes its call count or order, these will shift.
	var gotNext [8]int
	for i := range gotNext {
		gotNext[i] = rng.Intn(1_000_000)
	}
	// Golden values — locked against BUG-01 seed DB invalidation.
	// Generated by running this test with placeholder zeros and recording
	// the `got` output. Do NOT regenerate to make a failing test pass.
	wantNext := [8]int{
		77160, 849536, 37512, 312194, 335532, 812429, 282919, 437978,
	}
	if gotNext != wantNext {
		t.Errorf("RNG consumption order changed — BUG-01 seed DB invalidated.\n got = %v\nwant = %v", gotNext, wantNext)
	}
}

// TestAllWavesFired exercises the one-way latches and AllWavesFired gate.
func TestAllWavesFired(t *testing.T) {
	r := NewRoomState(0)
	if !AllWavesFired(r) {
		t.Fatal("AllWavesFired should be true when there are no pending waves")
	}
	r.PendingWaves = []PendingWave{{Fired: false}, {Fired: true}}
	if AllWavesFired(r) {
		t.Fatal("AllWavesFired should be false when any pending wave has not fired")
	}
	r.PendingWaves[0].Fired = true
	if !AllWavesFired(r) {
		t.Fatal("AllWavesFired should be true once every pending wave has fired")
	}
}

// TestAdvanceWavesArmAndFire exercises the arm/fire pipeline with a wave
// that instantiates a single mob after its delay elapses.
func TestAdvanceWavesArmAndFire(t *testing.T) {
	r := NewRoomState(0)
	r.InitialPop = 2
	// Fake two living enemies so livingCount starts at 2.
	r.Enemies[1] = &EnemyState{EntityID: 1, HP: 1, AIState: AIPatrol}
	r.Enemies[2] = &EnemyState{EntityID: 2, HP: 1, AIState: AIPatrol}
	r.PendingWaves = []PendingWave{{
		TriggerRemaining: 1,
		ArmDelayJitter:   0,
		Mobs: []PrecomputedMob{{
			Type: EnemyGrunt,
			Seed: MobSeed{SpawnX: 100, SpawnY: 100},
		}},
	}}

	now := time.Unix(1_700_000_000, 0)

	// Living = 2 > trigger 1: should NOT arm.
	spawned := AdvanceWaves(r, now)
	if r.PendingWaves[0].Armed || len(spawned) != 0 {
		t.Fatal("wave should not arm while livingCount > trigger")
	}

	// Kill enemy 2 → living = 1 ≤ trigger 1: should arm this tick, not fire.
	r.Enemies[2].AIState = AIDead
	spawned = AdvanceWaves(r, now)
	if !r.PendingWaves[0].Armed {
		t.Fatal("wave should arm when livingCount drops to trigger")
	}
	if r.PendingWaves[0].Fired || len(spawned) != 0 {
		t.Fatal("wave should not fire on the same tick it arms")
	}
	wantFireAt := now.Add(time.Duration(WaveArmDelayMs) * time.Millisecond)
	if !r.PendingWaves[0].FireAt.Equal(wantFireAt) {
		t.Fatalf("FireAt = %v; want %v", r.PendingWaves[0].FireAt, wantFireAt)
	}

	// One-way latch: resurrect enemy 2 (living back to 2). Wave stays armed.
	r.Enemies[2].AIState = AIPatrol
	spawned = AdvanceWaves(r, now)
	if !r.PendingWaves[0].Armed {
		t.Fatal("armed wave should stay armed even if livingCount rises")
	}
	if len(spawned) != 0 {
		t.Fatal("wave should not fire before FireAt")
	}

	// Advance past FireAt → wave fires.
	future := wantFireAt.Add(10 * time.Millisecond)
	spawned = AdvanceWaves(r, future)
	if !r.PendingWaves[0].Fired || len(spawned) != 1 {
		t.Fatalf("wave should fire when now >= FireAt; Fired=%v spawned=%v", r.PendingWaves[0].Fired, spawned)
	}
	if len(r.Enemies) != 3 {
		t.Fatalf("expected 3 enemies after fire (2 initial + 1 wave), got %d", len(r.Enemies))
	}

	// Idempotent: firing again does nothing.
	spawned = AdvanceWaves(r, future.Add(time.Second))
	if len(spawned) != 0 {
		t.Fatal("fired wave should not spawn again")
	}
}

// TestAdvanceWavesLaterWaveWaitsForEarlierToFire is the regression for the
// "waves 1 and 2 spawn at the same time" bug: during wave 0's arm-delay
// window the player can keep killing enemies, and livingCount drops past
// wave 1's threshold while wave 0's reinforcements are still pending. The
// fix gates wave 1's arm on wave 0 having fired, so its threshold is only
// checked after wave 0's mobs are on the field.
func TestAdvanceWavesLaterWaveWaitsForEarlierToFire(t *testing.T) {
	r := NewRoomState(0)
	r.InitialPop = 6
	for i := uint32(1); i <= 6; i++ {
		r.Enemies[i] = &EnemyState{EntityID: i, HP: 1, AIState: AIPatrol}
	}
	r.PendingWaves = []PendingWave{
		{TriggerRemaining: 3, ArmDelayJitter: 0, Mobs: []PrecomputedMob{{
			Type: EnemyGrunt,
			Seed: MobSeed{SpawnX: 200, SpawnY: 200},
		}}},
		{TriggerRemaining: 1, ArmDelayJitter: 0, Mobs: []PrecomputedMob{{
			Type: EnemyGrunt,
			Seed: MobSeed{SpawnX: 300, SpawnY: 200},
		}}},
	}

	now := time.Unix(1_700_000_000, 0)

	// Drop living to 3 → wave 0 arms, wave 1 must NOT arm yet (its earlier
	// wave hasn't fired).
	for _, id := range []uint32{4, 5, 6} {
		r.Enemies[id].AIState = AIDead
	}
	if spawned := AdvanceWaves(r, now); len(spawned) != 0 {
		t.Fatalf("no wave should fire on the arm tick; got %v", spawned)
	}
	if !r.PendingWaves[0].Armed {
		t.Fatal("wave 0 should arm at living = trigger 0")
	}
	if r.PendingWaves[1].Armed {
		t.Fatal("wave 1 must not arm while wave 0 is still pending — its threshold isn't meaningful yet")
	}

	// Player keeps killing during wave 0's arm-delay window — living drops
	// to 0, comfortably under wave 1's trigger. Wave 1 still must not arm.
	for _, id := range []uint32{1, 2, 3} {
		r.Enemies[id].AIState = AIDead
	}
	if spawned := AdvanceWaves(r, now.Add(500*time.Millisecond)); len(spawned) != 0 {
		t.Fatalf("no wave should fire before FireAt; got %v", spawned)
	}
	if r.PendingWaves[1].Armed {
		t.Fatal("wave 1 must not arm before wave 0 fires, even with living = 0")
	}

	// Wave 0 fires when its FireAt elapses. Wave 1 must not fire on the
	// same tick — the arm gate keeps it pending until next tick at
	// earliest, and even then it needs its own arm-delay before firing.
	fire := now.Add(time.Duration(WaveArmDelayMs+10) * time.Millisecond)
	spawned := AdvanceWaves(r, fire)
	if len(spawned) != 1 {
		t.Fatalf("expected wave 0 to fire alone; spawned %d this tick", len(spawned))
	}
	if !r.PendingWaves[0].Fired {
		t.Fatal("wave 0 should be marked fired")
	}
	if r.PendingWaves[1].Fired {
		t.Fatal("wave 1 must not fire on the same tick as wave 0")
	}
}

// TestBroadcastPackAggro verifies the on-damage radius-based aggro flip.
func TestBroadcastPackAggro(t *testing.T) {
	r := NewRoomState(0)
	victim := &EnemyState{EntityID: 1, X: 500, Y: 500, AIState: AIPatrol, HP: 1}
	nearby := &EnemyState{EntityID: 2, X: 600, Y: 500, AIState: AIPatrol, HP: 1}        // within 250px
	farAway := &EnemyState{EntityID: 3, X: 900, Y: 500, AIState: AIPatrol, HP: 1}       // outside
	alreadyAggro := &EnemyState{EntityID: 4, X: 600, Y: 600, AIState: AIAggro, HP: 1}   // within, but already aggro
	dead := &EnemyState{EntityID: 5, X: 510, Y: 510, AIState: AIDead, HP: 0}            // within, but dead
	r.Enemies[1] = victim
	r.Enemies[2] = nearby
	r.Enemies[3] = farAway
	r.Enemies[4] = alreadyAggro
	r.Enemies[5] = dead

	BroadcastPackAggro(r, victim.X, victim.Y, victim.EntityID)

	if nearby.AIState != AIAggro {
		t.Errorf("nearby mob should flip to AIAggro; got %v", nearby.AIState)
	}
	if farAway.AIState != AIPatrol {
		t.Errorf("far mob should stay AIPatrol; got %v", farAway.AIState)
	}
	if alreadyAggro.AIState != AIAggro {
		t.Errorf("already-aggro mob should stay AIAggro; got %v", alreadyAggro.AIState)
	}
	if dead.AIState != AIDead {
		t.Errorf("dead mob should stay AIDead; got %v", dead.AIState)
	}
	if victim.AIState != AIAggro {
		t.Errorf("victim should flip to AIAggro on damage broadcast; got %v", victim.AIState)
	}
}
